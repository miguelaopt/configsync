/**
 * Builds the companion as single executables — no Node on the user's machine:
 *   public/csync-windows-x64.exe   public/csync-linux-x64   public/install.sh
 *
 * Bundle (esbuild → one CommonJS file) → Node SEA blob → inject into the official Node binary
 * of each platform (downloaded from nodejs.org, cached in .cache/). Windows' node.exe is
 * Authenticode-signed; its signature is stripped first so the result is plainly unsigned
 * rather than "signed, but tampered".
 */
import { execFileSync } from "node:child_process";
import { createHash } from "node:crypto";
import {
  chmodSync,
  copyFileSync,
  createWriteStream,
  existsSync,
  mkdirSync,
  readFileSync,
  unlinkSync,
  writeFileSync,
} from "node:fs";
import { pipeline } from "node:stream/promises";
import { Readable } from "node:stream";
import { join } from "node:path";

const NODE = "v24.21.0"; // LTS; bump deliberately, it is what users run
// SHA-256 of each archive, from https://nodejs.org/dist/<NODE>/SHASUMS256.txt. Pinned here so a
// tampered download (or mirror) can never become the binary we ship; update them with NODE.
const SHA256 = {
  "linux-x64": "fd8e59d5a511510f6a298afb548f18c7d2b1be404d8b4a27d94fbe49f56cb2d6",
  "linux-x64-musl": "34ab095af8efe9018f21489d3dc19871fb5edd4f130a71469b69c05fd4e32a5e",
  "win-x64": "158f7685b44de51f6c0df1d153526cbcd3e1bc739a8dfc607721cef75de9e541",
};
const FUSE = "NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2";
const root = process.cwd();
const cache = join(root, ".cache", "companion");
const out = join(root, "public");
mkdirSync(cache, { recursive: true });

const sh = (cmd, args, opts = {}) => execFileSync(cmd, args, { stdio: "inherit", ...opts });

async function fetchTo(url, file, sha256) {
  if (!existsSync(file)) {
    console.log(`↓ ${url}`);
    const res = await fetch(url);
    if (!res.ok) throw new Error(`${url}: ${res.status}`);
    await pipeline(Readable.fromWeb(res.body), createWriteStream(file));
  }
  const actual = createHash("sha256").update(readFileSync(file)).digest("hex");
  if (actual !== sha256) {
    unlinkSync(file);
    throw new Error(`${file}: sha256 ${actual} does not match the pinned ${sha256}`);
  }
}

/** Official Node for a platform; returns the path of the bare binary. */
async function nodeBinary(platform) {
  const name = `node-${NODE}-${platform}`;
  const bin = join(cache, platform === "win-x64" ? `${name}.exe` : name);
  if (existsSync(bin)) return bin;
  if (platform === "win-x64") {
    const zip = join(cache, `${name}.zip`);
    await fetchTo(`https://nodejs.org/dist/${NODE}/${name}.zip`, zip, SHA256[platform]);
    sh("unzip", ["-q", "-o", "-j", zip, `${name}/node.exe`, "-d", cache]);
    copyFileSync(join(cache, "node.exe"), bin);
  } else {
    const tar = join(cache, `${name}.tar.xz`);
    await fetchTo(`https://nodejs.org/dist/${NODE}/${name}.tar.xz`, tar, SHA256[platform]);
    sh("tar", ["-xJf", tar, "-C", cache, "--strip-components=2", `${name}/bin/node`]);
    copyFileSync(join(cache, "node"), bin);
  }
  return bin;
}

/** Drops the Authenticode signature: zero the security data directory, cut the trailing cert. */
function stripSignature(exe) {
  const buf = readFileSync(exe);
  const pe = buf.readUInt32LE(0x3c);
  if (buf.readUInt32LE(pe) !== 0x00004550) throw new Error("not a PE file");
  const optional = pe + 24;
  const pe32plus = buf.readUInt16LE(optional) === 0x20b;
  const securityDir = optional + (pe32plus ? 112 : 96) + 4 * 8;
  const certOffset = buf.readUInt32LE(securityDir);
  const certSize = buf.readUInt32LE(securityDir + 4);
  if (!certOffset) return;
  buf.writeUInt32LE(0, securityDir);
  buf.writeUInt32LE(0, securityDir + 4);
  writeFileSync(exe, certOffset + certSize === buf.length ? buf.subarray(0, certOffset) : buf);
}

// 1. one CommonJS file
const bundle = join(cache, "csync.cjs");
sh(join(root, "node_modules", ".bin", "esbuild"), [
  "companion/bin/csync.mjs",
  "--bundle",
  "--platform=node",
  "--format=cjs",
  `--target=node${NODE.slice(1).split(".")[0]}`,
  `--outfile=${bundle}`,
  "--log-level=warning",
  "--log-override:empty-import-meta=silent",
]);

// 2. the SEA blob, generated by the same Node version that will run it. The glibc build cannot
// execute on a musl host (the Docker image is Alpine), so the blob is made with the musl build
// there; users still get the glibc binary.
const musl = existsSync("/etc/alpine-release");
const linuxNode = await nodeBinary(musl ? "linux-x64-musl" : "linux-x64");
const seaConfig = join(cache, "sea-config.json");
writeFileSync(
  seaConfig,
  JSON.stringify({
    main: bundle,
    output: join(cache, "csync.blob"),
    disableExperimentalSEAWarning: true,
  }),
);
sh(linuxNode, ["--experimental-sea-config", seaConfig]);

// 3. inject into each platform's binary
const postject = join(root, "node_modules", ".bin", "postject");
const targets = [
  ["linux-x64", "csync-linux-x64"],
  ["win-x64", "csync-windows-x64.exe"],
];
for (const [platform, file] of targets) {
  const dest = join(out, file);
  copyFileSync(await nodeBinary(platform), dest);
  if (platform === "win-x64") stripSignature(dest);
  sh(postject, [dest, "NODE_SEA_BLOB", join(cache, "csync.blob"), "--sentinel-fuse", FUSE], {
    stdio: "pipe",
  });
  chmodSync(dest, 0o755);
  console.log(`✓ ${dest}`);
}

// 4. the Linux one-liner
writeFileSync(
  join(out, "install.sh"),
  `#!/bin/sh
# ConfigSync companion for Linux: puts csync in ~/.local/bin. Run: curl -fsSL <origin>/install.sh | sh
set -e
origin="\${CSYNC_ORIGIN:-https://configsync.app}"
dir="\${HOME}/.local/bin"
mkdir -p "$dir"
curl -fsSL "$origin/csync-linux-x64" -o "$dir/csync"
chmod +x "$dir/csync"
echo "csync installed to $dir/csync"
case ":$PATH:" in *":$dir:"*) ;; *) echo "Add $dir to your PATH (most distros do after a re-login), then: csync login $origin";; esac
`,
);
console.log("✓ public/install.sh");
